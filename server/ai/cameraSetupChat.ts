// Чат-помощник по подключению камер — отвечает ТОЛЬКО в рамках нашей
// инструкции (см. SETUP_DOCS), не общий ассистент. Переиспользует
// chatComplete как есть, деградирует так же тихо, как остальные ИИ-фичи
// (нет ключа/сеть недоступна — вызывающий код показывает понятную ошибку).
import { chatComplete, AiUnavailableError } from "./routerai";
import type { CameraVendor } from "@prisma/client";
import { CAMERA_VENDORS } from "@/lib/cameraVendors";

export class CameraChatError extends Error {}

const SETUP_DOCS = `
Раздел «Камеры» в ТоргОС — просмотр видео с регистратора магазина, живьём и в записи.

Топология: регистратор стоит в магазине за NAT провайдера, порты наружу открывать нельзя (это небезопасно).
Поэтому рядом с регистратором нужен агент — небольшой мини-ПК или Raspberry Pi. Агент сам подключается к
нашему серверу, порты на роутере магазина трогать не нужно.

Установка агента — одна команда (токен и готовую команду с ним смотрите в настройках камер, кнопка
«Добавить агента»):
  curl -fsSL https://<домен>/agent-dist/install.sh | sudo bash -s -- <ТОКЕН> <АДРЕС_СЕРВЕРА>
Через несколько секунд агент появится «онлайн» в настройках.

Добавление регистратора: в настройках камер — «Добавить устройство», указать вендор (Dahua/Hikvision/другой),
адрес регистратора в локальной сети магазина, логин и пароль, к какому агенту подключён. Дальше — «Добавить
канал» на каждую физическую камеру (номер канала на регистраторе + название, например «Касса», «Склад»).

Частая проблема: у регистратора (особенно у старых Dahua) сбиты системные часы — тогда поиск архива по
датам работать не будет. В настройках устройства есть кнопка «Проверить подключение» — она же сверяет часы
регистратора с нашим сервером и покажет предупреждение, если расхождение больше пары минут.

Пароль регистратора хранится в зашифрованном виде, агент его не видит и не хранит — весь трафик с учётными
данными собирает сервер, агент только передаёт уже готовые запросы.
`.trim();

export async function askCameraSetupAssistant(
  question: string,
  deviceContext?: { vendor: CameraVendor; host: string },
): Promise<string> {
  const clean = question.trim();
  if (clean.length < 3) throw new CameraChatError("Опишите вопрос подробнее");

  const vendorLine = deviceContext
    ? `\n\nТекущее устройство пользователя: вендор ${CAMERA_VENDORS[deviceContext.vendor].label}, адрес в локальной сети ${deviceContext.host}.`
    : "";

  const system =
    "Ты — техподдержка ТоргОС, помогаешь подключить камеры видеонаблюдения магазина к системе. Отвечай " +
    "ТОЛЬКО по инструкции ниже, простым деловым русским языком, без канцелярита и без markdown-разметки. " +
    "Если вопрос не про подключение камер к ТоргОС — вежливо скажи, что помогаешь только с этим.\n\n" +
    SETUP_DOCS + vendorLine;

  try {
    return await chatComplete(
      [
        { role: "system", content: system },
        { role: "user", content: clean },
      ],
      { maxTokens: 600 },
    );
  } catch (e) {
    if (e instanceof AiUnavailableError) throw new CameraChatError("ИИ-помощник временно недоступен, попробуйте позже");
    throw e;
  }
}
